// Turns lib/workspace-summary.ts into plain JavaScript source that the plugin
// sends to Lobu's query_sdk. Run with `bun run generate`.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");

export function lobuScriptsSource(): string {
  const typescript = readFileSync(join(root, "lib/workspace-summary.ts"), "utf8");
  const javascript = new Bun.Transpiler({ loader: "ts", target: "browser" }).transformSync(typescript);
  // Lobu runs one module whose default export is the entry point.
  return javascript.replaceAll("export async function ", "async function ").trim();
}

export function generatedModule(): string {
  return [
    "// Generated by scripts/generate-lobu-scripts.ts from lib/workspace-summary.ts. Do not edit.",
    `export const LOBU_SCRIPTS_SOURCE = ${JSON.stringify(lobuScriptsSource())};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  writeFileSync(join(root, "lib/lobu-scripts.generated.ts"), generatedModule());
}
